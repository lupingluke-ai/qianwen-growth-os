/** 按角色过滤章节与小节（缺省 roles 表示全员可见） */
export function helpChaptersForRole(role: HelpRole): HelpChapter[] {
  return HELP_CHAPTERS
    .filter(chapter => !chapter.roles || chapter.roles.includes(role))
    .map(chapter => ({ ...chapter, sections: chapter.sections.filter(section => !section.roles || section.roles.includes(role)) }));
}

/** 展开章节的全部可搜索文本行（标题、摘要、小节标题、正文与步骤） */
export function helpChapterLines(chapter: HelpChapter): string[] {
  return [
    chapter.title,
    chapter.summary,
    ...chapter.sections.flatMap(section => [section.heading || "", ...(section.paragraphs || []), ...(section.steps || [])]),
  ].filter(Boolean);
}
